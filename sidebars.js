/*
 * Docs layout:
 *
 *   docs/<package>/<version>/<locale>/<section>/<page>.md
 *
 *   <package>  npm name, mirrored in folders: docs/disfox, docs/@disfox/errors
 *   <version>  "latest" or a semver folder such as "0.1.5"
 *   <locale>   language folder such as "en" or "pt"
 *
 * Each <package>/<version>/<locale> folder gets its own sidebar, rooted at that
 * folder. This way the menu only shows the current group and the package,
 * version and language folders never appear as entries in the menu.
 */
const fs = require('node:fs');
const path = require('node:path');

const DOCS_DIR = path.join(__dirname, 'docs');
const VERSION_FOLDER = /^(latest|\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)$/;

function listDirectories(absoluteDir) {
  return fs
    .readdirSync(absoluteDir, {withFileTypes: true})
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

// Walks the docs tree and returns one sidebar per <package>/<version>/<locale>.
function buildSidebars(relativeDir = '', sidebars = {}) {
  for (const name of listDirectories(path.join(DOCS_DIR, relativeDir))) {
    const relativePath = relativeDir ? `${relativeDir}/${name}` : name;
    if (VERSION_FOLDER.test(name)) {
      for (const locale of listDirectories(path.join(DOCS_DIR, relativePath))) {
        const key = `${relativePath}/${locale}`;
        sidebars[key] = [{type: 'autogenerated', dirName: key}];
      }
    } else {
      buildSidebars(relativePath, sidebars);
    }
  }
  return sidebars;
}

module.exports = buildSidebars();
